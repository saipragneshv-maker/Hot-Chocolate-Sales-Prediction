import pandas as pd

import numpy as np

import matplotlib.pyplot as plt

hot_choco = pd.read_csv(r"/content/06_temperature_vs_hotchocolate_sales.csv")

hot_choco.head()

hot_choco.keys()

hot_choco.dtypes

columns = ['temperature_C', 'humidity_pct', 'wind_speed_kmh', 'is_weekend',
       'hotchoc_sales']

hot_choco = hot_choco.apply(pd.to_numeric,errors = "coerce")
hot_choco.dtypes

hot_choco.isna().sum()

hot_choco["temperature_C"] = hot_choco["temperature_C"].fillna(hot_choco["temperature_C"].mean())
hot_choco["humidity_pct"] = hot_choco["humidity_pct"].fillna(hot_choco["humidity_pct"].mean())
hot_choco["wind_speed_kmh"] = hot_choco["wind_speed_kmh"].fillna(hot_choco["wind_speed_kmh"].mean())
hot_choco["is_weekend"] = hot_choco["is_weekend"].fillna(hot_choco["is_weekend"].mean())
hot_choco["hotchoc_sales"] = hot_choco["hotchoc_sales"].fillna(hot_choco["hotchoc_sales"].mean())

hot_choco.isna().sum()

hot_choco.duplicated().sum()

hot_choco = hot_choco.drop_duplicates()
hot_choco.duplicated().sum()

hot_choco.corr()

import seaborn as sns
sns.regplot(x="temperature_C",y="hotchoc_sales",data = hot_choco)

from sklearn.model_selection import train_test_split
x = hot_choco[['temperature_C', 'humidity_pct', 'wind_speed_kmh', 'is_weekend']]
y = hot_choco["hotchoc_sales"]
x_train,x_test,y_train,y_test = train_test_split(
    x,y,test_size = 0.2,random_state = 42
)

from sklearn.linear_model import LinearRegression
model = LinearRegression()
model.fit(x_train,y_train)
y_pred = model.predict(x_test)
print(y_pred)

error = y_test - y_pred
print("error:",error)

from sklearn.metrics import mean_absolute_error,mean_squared_error,r2_score
mae = mean_absolute_error(y_test,y_pred)
mse = mean_squared_error(y_test,y_pred)
rmse = np.sqrt(mse)
r2 = r2_score(y_test,y_pred)
print("mae: ",mae)
print("Mse: ",mse)
print("Rmse: ",rmse)
print("r2_score: ",r2)